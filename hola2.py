# operradores de arismeticos

a= 10
b= 5

# suma 
suma = a + b
print("la summa de a y b es:",suma )

# resta
resta = a - b   
print("la resta de a y b es:",resta)

# multiplicacion
multiplicacion = a * b
print("la multiplicacion de a y b es:",multiplicacion)  

# division
division = a / b     
print("la division de a y b es:",division)
# modulo
modulo = a % b
print("el modulo de a y b es:",modulo)

